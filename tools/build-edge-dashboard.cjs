const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const functionsRoot = path.join(root, 'supabase', 'functions');
const outputRoot = path.join(root, 'supabase', '.temp', 'dashboard');
const read = name => fs.readFileSync(path.join(functionsRoot, name), 'utf8').replace(/^\uFEFF/, '');

try {
  const shared = ['_shared/auth.ts', '_shared/ai-controls.ts'].map(name =>
    read(name).replace(/^export (?=(?:async )?function |class )/gm, '')).join('\n\n');

  for (const name of ['study-assistant', 'analyze-course-file']) {
    let source = read(`${name}/index.ts`);
    const standalone = source.startsWith('// Generated by npm run build:edge:dashboard.');
    if (standalone) {
      // Preserve a standalone entrypoint copied into the source directory,
      // including any edits, without adding a second copy of shared helpers.
      source = source.replace(/^\/\/ Generated[^\n]*\r?\n\/\/ Self-contained[^\n]*\r?\n/, '')
        .replace(/^export \{\};\r?\n/gm, '').trimStart();
    } else {
      for (const module of ['auth', 'ai-controls']) {
        const pattern = new RegExp(`^import \\{[^\\n]+\\} from "\\.\\./_shared/${module}\\.ts";\\r?\\n`, 'm');
        if (!pattern.test(source)) throw new Error(`Unexpected ${module} import in ${name}; review the source before generating.`);
        source = source.replace(pattern, '');
      }
    }
    const result = `// Generated by npm run build:edge:dashboard. Edit the source modules, then regenerate.\n` +
      `// Self-contained Dashboard entrypoint: no local imports or embedded secrets.\n` +
      `export {};\n\n${standalone ? source : `${shared}\n\n${source}`}`;
    if (/^import\s/m.test(result)) throw new Error(`Unresolved imports remain in ${name}; no Dashboard entrypoint was written.`);
    const outputDir = path.join(outputRoot, name);
    fs.mkdirSync(outputDir, { recursive: true });
    const output = path.join(outputDir, 'index.ts');
    fs.writeFileSync(output, result);
    console.log(`${name}: ${output}`);
  }
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
